    /// Plan changes to a resource
    pub async fn plan_resource(
        &self,
        resource_name: &str,
        current_state: Option<&ResourceOutput>,
        desired_input: &ResourceInput,
    ) -> Result<ResourcePlan> {
        match resource_name {
            "queue_attributes" => {
                self.plan_queue_attributes(current_state, desired_input)
                    .await
            }
            "message" => self.plan_message(current_state, desired_input).await,
            "message_batch" => self.plan_message_batch(current_state, desired_input).await,
            "queue" => self.plan_queue(current_state, desired_input).await,
            "queue_url" => self.plan_queue_url(current_state, desired_input).await,
            _ => Err(hemmer_core::HemmerError::Provider(format!(
                "Unknown resource type: {}.{}",
                "sqs", resource_name
            ))),
        }
    }

